export type TaskPaymentRef = { amount: number; paidOn: string };

export type DocTask = {
  id: string;
  /** Строки расшифровки долга (debt-trace L01…L18), к которым относится задача. */
  lines: string[];
  kind: DocKind;
  owner: TaskOwner;
  /** «Что найти». */
  title: string;
  /** «К какой записи» — подпись; ссылка строится из данных. */
  record: string;
  /** Сумма под вопросом, ₽ (null — подставляется долг из loadSupplierDebt). */
  amount: number | null;
  /** Конкретные оплаты в базе (по сумме и дате): задача закрыта, когда каждая подтверждена или к ней приложена платёжка. */
  payments?: TaskPaymentRef[];
  /** Закупки (номера), на которых ищем приложенный документ. */
  purchases?: string[];
  /** Оплаты, чьи документы тоже считаются (напр. аванс без привязки к закупке). */
  alsoPayments?: TaskPaymentRef[];
  /** Искать по всей организации (акт сверки, файл счёта №37). */
  orgWide?: boolean;
  accepts?: DriveDocTypeKey[];
  /** Регулярное выражение (без флагов, ищется без учёта регистра) по названию и номеру документа. */
  needle?: string;
  /** Сколько документов нужно (по умолчанию 1). */
  min?: number;
  /** Срок оплаты/документа (ГГГГ-ММ-ДД) и пояснение к нему. */
  due?: string;
  dueNote?: string;
  /** Оплата уже учтена в базе (напр. по решению владельца): срок «просрочено» не показываем, просим только платёжку и дату. */
  accountedNote?: string;
  /** Документ появится только после поставки — задача справочная, в число открытых не входит. */
  later?: boolean;
  /** Эту оплату разом закрывает выписка р/с Меркури Мода за период (одна выписка — шесть оплат). */
  viaStatement?: boolean;
  /** «Проверено: искали в папках …» (на дату SEARCH_DATE). */
  checked: string;
};

