export type LetterTask = { title: string; record: string; amount: number | null; kind: DocKind; dueText: string | null; checked: string; later: boolean };

const rub = (n: number) => `${n.toLocaleString("ru-RU", { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ₽`;
const isoRu = (iso: string) => `${iso.slice(8, 10)}.${iso.slice(5, 7)}.${iso.slice(0, 4)}`;

/** Готовый текст «Письмо для …» со списком недостающих документов (markdown). Открытые — нумерованным списком, ожидающие поставки — отдельно. */
export function buildLetter(owner: "mm" | "vellmex", tasks: LetterTask[], todayIso: string): string {
  const open = tasks.filter((t) => !t.later);
  const later = tasks.filter((t) => t.later);
  const sum = open.reduce((s, t) => s + (t.amount ?? 0), 0);
  const head =
    owner === "mm"
      ? [
          "# Письмо для бухгалтерии ООО «Меркури Мода»",
          "",
          `Дата: ${isoRu(todayIso)}`,
          "",
          "Здравствуйте! Для сверки долга перед Веллмех и подтверждения оплат просим выслать из банк-клиента (р/с 40702810000010002483, банк «Сервис Резерв») платёжные поручения или выписки за указанные даты. В общем хранилище («мех») таких документов нет.",
          "",
          "Если разом выгрузить выписку р/с за 30.03.2026 — 20.07.2026, она закроет шесть оплат на 102 227 020,54 ₽ (отмечены ниже), а выписка за сентябрь 2025 — июль 2026 — большую часть остальных.",
        ]
      : [
          "# Письмо для Веллмех (бухгалтерия, подписант Вельмакина И.Е.)",
          "",
          `Дата: ${isoRu(todayIso)}`,
          "",
          "Здравствуйте! Для сверки взаиморасчётов просим прислать документы из списка ниже (счета, УПД, письмо о разнесении аванса, акт сверки). В нашем хранилище их нет.",
        ];
  const lines: string[] = [...head, "", `## Нужно прислать (${open.length}${sum > 0 ? `, сумма под вопросом ${rub(sum)}` : ""})`, ""];
  open.forEach((t, i) => {
    lines.push(`${i + 1}. **${t.title}**`);
    lines.push(`   - К чему относится: ${t.record}`);
    if (t.amount != null) lines.push(`   - Сумма: ${rub(t.amount)}`);
    if (t.dueText) lines.push(`   - Срок: ${t.dueText}`);
    lines.push(`   - Что уже искали: ${t.checked}`);
  });
  if (open.length === 0) lines.push("Недостающих документов нет.");
  if (later.length) {
    lines.push("", `## После поставки (${later.length}) — пока не требуется`, "");
    later.forEach((t) => lines.push(`- ${t.title} — ${t.record}${t.amount != null ? `, ${rub(t.amount)}` : ""}`));
  }
  lines.push("", "Просим прислать сканы или файлы в ответном письме; мы загрузим их в систему учёта, задача закроется сама.");
  return lines.join("\n");
}
