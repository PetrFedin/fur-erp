/** Вид действия: manual — вносят и правят вручную; auto — считается само; both — и то и другое. */
export type Kind = "manual" | "auto" | "both";
export type Branch = { title: string; text: string; href: string; kind: Kind };
/** Сущность, которую создаёт шаг: ссылка на список и (если есть) на карточку записи — page.tsx подставляет последнюю созданную. */
export type CardKey = "purchase" | "lot" | "order" | "batch" | "payment" | "paymentProd" | "shipment" | "model" | "fitting" | "budget" | "supplier";
export type Entity = { name: string; text: string; list: string; card?: CardKey; /** manual — создают руками; auto — собирается из внесённого (создать вручную нельзя); both — и то и другое. */ kind: Kind };
export type Step = {
  title: string;
  /** Подпись под названием блока на схеме (необязательно). */
  sub?: string;
  /** Пояснение про порядок: что может идти раньше или позже. */
  note?: string;
  /** Что создаётся на этом шаге и куда зайти: список и карточка записи. */
  entities: Entity[];
  /** Раздел меню, куда ведёт кнопка. */
  href: string;
  open: string;
  /** Как это делается — короткие шаги простыми словами. */
  how: string[];
  /** Что вносят руками (подробно). */
  enter: string[];
  /** Что можно изменить (где именно — на карточке записи). */
  edit: string[];
  /** Что считается автоматически. */
  auto: string[];
  /** Что получаем в итоге (и куда это идёт дальше). */
  get: string[];
  /** Что пересчитается в других местах, если здесь поправить данные. */
  recalc: string[];
  /** Откуда берутся данные — предыдущие шаги. */
  from?: string;
  branches: Branch[];
};

