function main() {
  if (ROLLBACK) {
    if (!existsSync(BEFORE)) { console.log("Копии до нет — откатывать нечего."); return; }
    if (APPLY) { copyFileSync(BEFORE, FILE); console.log("Файл возвращён из копии."); } else console.log("Будет возвращён src/data/reconciliation.json из", BEFORE);
    return;
  }
  const raw = readFileSync(FILE, "utf-8");
  const data = JSON.parse(raw) as Data;
  const table: string[][] = [];
  const log = (inv: string, what: string, basis: string) => table.push([inv, what, basis]);
  const byId = new Map(data.groups.map((g) => [g.id, g]));
  let touchedInv = 0;

  // ---- 1) платежи счетов ← реестр списаний
  for (const inv of data.invoices) {
    if (inv.superseded || !inv.no) continue;
    const manual = MANUAL[inv.id];
    const cands = REG.filter((r) => (manual ? r[0] === manual : r[5] === inv.no && near(r[3], inv.amountRub) && (!inv.date || (r[2] >= inv.date && dayDiff(r[2], inv.date) <= 400))));
    if (!cands.length) continue;
    const r = cands.length === 1 ? cands[0] : cands.sort((a, b) => dayDiff(a[2], inv.date ?? a[2]) - dayDiff(b[2], inv.date ?? b[2]))[0];
    const [row, pp, date, amount] = r;
    const src = `${REG_TAG}, стр. ${row} (${DATE_TAG}): п/п №${pp} от ${dmy(date)}, ${rub(amount)}`;
    // существующая запись об оплате этого счёта: та же сумма (или тот же п/п)
    const ex = inv.paid.find((p) => p.ppNo === pp && near(p.amountRub, amount)) ?? inv.paid.find((p) => near(p.amountRub, amount));
    if (ex && ex.basis === "pp" && ex.evidence === "fact" && ex.ppNo === pp && ex.date === date && String(ex.source).includes(REG_TAG)) continue; // уже внесено
    if (ex && ex.basis === "pp" && ex.evidence === "fact" && ex.ppNo === pp && ex.date === date) { // банк и реестр сверки уже совпадали: только добавим источник
      ex.source = `${ex.source}; ${src}`;
      log(`№${inv.no} от ${dmy(inv.date ?? "")}`, `источник: + реестр списаний (стр. ${row})`, src);
      touchedInv++;
      continue;
    }
    const before = ex ? `${ex.basis ?? "—"}/${ex.evidence}${ex.ppNo ? ` п/п ${ex.ppNo}` : ""}${ex.date ? ` ${dmy(ex.date)}` : ""}` : "нет оплаты";
    if (ex) {
      const old = ex.source;
      Object.assign(ex, { date, ppNo: pp, basis: "pp", evidence: "fact", source: `${src}; прежде: ${old}` });
      delete ex.dateApprox;
    } else {
      inv.paid.push({ date, amountRub: amount, ppNo: pp, basis: "pp", evidence: "fact", source: src });
    }
    log(`№${inv.no} от ${dmy(inv.date ?? "")} (${rub(inv.amountRub)})`, `${before} → п/п ${pp} ${dmy(date)} (факт банка)`, src);
    touchedInv++;
  }

  // ---- 2) группы
  const lacking: string[] = [];
  for (const [gid, op] of Object.entries(OPS)) {
    const g = byId.get(gid);
    if (!g) { lacking.push(`группа ${gid}`); continue; }
    const tag = `Сверка с реестром списаний «Оплаты.xls» (${DATE_TAG}): ${op.note.replace(/^Реестр списаний «Оплаты\.xls»:?\s*/, "")}`;
    if ((g.notes ?? []).some((x) => x.startsWith("Сверка с реестром списаний «Оплаты.xls»"))) continue; // уже применено
    const was = `${g.status}`;
    if (op.status && g.status !== op.status) g.status = op.status;
    if (op.paidRub != null) g.doc.paidRub = op.paidRub;
    if (op.costRub != null) g.doc.costRub = op.costRub;
    for (const lab of op.checksOk ?? []) {
      const c = g.checks.find((x) => x.label.startsWith(lab));
      if (!c) lacking.push(`${gid}: проверка «${lab}»`); else c.ok = true;
    }
    for (const key of op.dropDiffs ?? []) {
      const i = g.diffs.findIndex((d) => d.what.startsWith(key));
      if (i < 0) lacking.push(`${gid}: расхождение «${key}»`); else g.diffs.splice(i, 1);
    }
    for (const key of op.dropManual ?? []) {
      const i = (g.manualReview ?? []).findIndex((m) => m.startsWith(key));
      if (i < 0) lacking.push(`${gid}: ручная проверка «${key}»`); else g.manualReview!.splice(i, 1);
    }
    for (const [key, add] of op.appendWhy ?? []) {
      const d = g.diffs.find((x) => x.what.startsWith(key));
      if (!d) lacking.push(`${gid}: расхождение (дополнить) «${key}»`); else d.why = `${d.why ?? ""}${add}`.trim();
    }
    g.notes = [...(g.notes ?? []), tag];
    table.push([`группа «${gid}»`, `${was !== g.status ? `статус ${was} → ${g.status}; ` : ""}${op.paidRub != null ? `оплачено по документам ${rub(op.paidRub)}; ` : ""}${op.costRub != null ? `стоимость по УПД ${rub(op.costRub)}; ` : ""}закрыто расхождений ${(op.dropDiffs ?? []).length}, ручных пунктов ${(op.dropManual ?? []).length}, проверок ${(op.checksOk ?? []).length}`, op.note]);
  }
  if (lacking.length) { console.error("НЕ НАЙДЕНО (патч не применён):\n- " + lacking.join("\n- ")); process.exit(1); }

  // ---- 3) блок «Перепроверка по документам»
  const rc = data.recheck;
  if (rc && !rc.found.some((x) => x.startsWith("19.10.2026 сверка с реестром списаний"))) {
    rc.date = "2026-10-19";
    for (const [prefix, to] of RECHECK_REPLACE) {
      const i = rc.found.findIndex((x) => x.startsWith(prefix));
      const j = rc.notFound.findIndex((x) => x.startsWith(prefix));
      if (i >= 0) { if (to) rc.found[i] = to; else rc.found.splice(i, 1); }
      else if (j >= 0) { if (to) rc.notFound[j] = to; else rc.notFound.splice(j, 1); }
      else { console.error(`НЕ НАЙДЕН пункт перепроверки «${prefix}»`); process.exit(1); }
    }
    rc.found.push(...RECHECK_FOUND.map((x) => x.replace("@@N_INV@@", String(touchedInv))));
    data.checkedAt = "2026-10-19";
    data.note = `${data.note} 19.10.2026: банковские п/п сверены с реестром списаний «Оплаты.xls» (67 п/п).`;
    table.push(["блок «Перепроверка по документам»", `найдено +${RECHECK_FOUND.length}, не найдено ${rc.notFound.length}`, "реестр списаний, акты сверки, письма"]);
  }

  console.log(`Счетов обновлено: ${touchedInv}; групп: ${Object.keys(OPS).length}`);
  for (const t of table) console.log(` · ${t[0]} | ${t[1]} | ${t[2].slice(0, 200)}`);
  if (!APPLY) { console.log("\nПробный прогон: файл не изменён. Для записи — --apply."); return; }
  if (!existsSync(BEFORE)) writeFileSync(BEFORE, raw);
  writeFileSync(FILE, JSON.stringify(data, null, 1) + (raw.endsWith("\n") ? "\n" : ""));
  console.log("Записано:", FILE);
}
main();
